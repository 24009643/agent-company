"""受保护属性(F5):封闭集 → 输入减脂 + 输出扫描。

封闭集可穷举,所以扫描能扫干净、减脂能锚定——与 F1 裁决(开放集,只能结构切除)相反。
两个诚实的坑:① 性别"男/女"单字易误伤,只做标签锚定扫描、不激进减脂;
② 年龄可由毕业年份反推,减脂删不净,靠输出扫描 + 人兜底。减脂是纵深防御,非唯一门。
对抗审查(F-A):民族/学历用收窄闭集,避免 [一-龥]{1,3}族、裸"一本"误杀"上班族/一本书"。
自检:python test_fairness.py
"""
import re

# 类别 -> 正则模式(封闭已知集)
_PROTECTED = {
    "年龄": [r"\d{1,2}\s*岁", r"(?:19|20)\d{2}\s*年\s*(?:生|出生)", r"出生[:：]"],
    "婚育": [r"已婚", r"未婚", r"离异", r"已育", r"未育", r"婚否", r"孕"],
    "籍贯": [r"籍贯", r"户籍", r"来自[一-龥]{2,4}(?:省|市)"],
    # ponytail: 民族=56 民族闭集枚举,替掉 [一-龥]{1,3}族(否则"上班族/追星族/打工族"全误杀 F-A);
    #           残留"水族馆"极少见,计入 filtered 交人复核,不静默吞
    "民族": [r"民族", r"(?:汉|回|满|蒙古|维吾尔|藏|壮|苗|彝|土家|布依|侗|瑶|白|哈尼|哈萨克|傣|黎|"
               r"傈僳|佤|畲|高山|拉祜|水|东乡|纳西|景颇|柯尔克孜|土|达斡尔|仫佬|羌|布朗|撒拉|毛南|"
               r"仡佬|锡伯|阿昌|普米|朝鲜|塔吉克|怒|乌孜别克|俄罗斯|鄂温克|德昂|保安|裕固|京|塔塔尔|"
               r"独龙|鄂伦春|赫哲|门巴|珞巴|基诺)族"],
    "照片": [r"照片", r"头像", r"相片", r"证件照"],
    # ponytail: "一本"需院校语境(否则"一本书/一本正经"误杀 F-A);二本/三本误友极少,保留裸词
    "学校档次": [r"985", r"211", r"双一流", r"一本(?:院校|大学|批|毕业|录取|线|重点)", r"二本", r"三本",
               r"双非", r"海归", r"留学归国", r"QS\s*\d", r"US[\.\-]?News", r"软科"],
    "性别": [r"性别[:：]?\s*[男女]"],  # 仅标签锚定;裸"男/女"不减脂,靠人兜底
}

# 减脂只处理多字符、好锚定的类别(性别单字不减脂,避免误伤"男朋友"等)
_REDACT_CATS = ("年龄", "婚育", "籍贯", "民族", "照片", "学校档次")


def scan_protected(text):
    """返回命中的受保护类别名(去重排序)。封闭集,扫得干净。"""
    text = text or ""
    hit = set()
    for cat, pats in _PROTECTED.items():
        if any(re.search(p, text) for p in pats):
            hit.add(cat)
    return sorted(hit)


def redact_protected(text):
    """输入减脂:把多字符可锚定的受保护项替换成「[已隐去]」。喂分析 LLM 前用。"""
    if not text:
        return text or ""
    for cat in _REDACT_CATS:
        for p in _PROTECTED[cat]:
            text = re.sub(p, "「[已隐去]」", text)
    return text
